import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const benchesDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const products = new Set(["codebench", "docbench", "streambench"]);
const product = process.argv[2];

if (!products.has(product)) {
  throw new Error(`Expected one bench name, got: ${product || "<empty>"}`);
}

const source = join(benchesDir, "shared", "webmcp-lifecycle.js");
const targetDir = join(benchesDir, product, "public");
const target = join(targetDir, "webmcp-lifecycle.js");

await mkdir(targetDir, { recursive: true });
const runtime = await readFile(source, "utf8");
const banner = "// Generated by benches/scripts/sync-webmcp.mjs from benches/shared/webmcp-lifecycle.js. Do not edit directly.\n";
await writeFile(target, `${banner}${runtime}`);
